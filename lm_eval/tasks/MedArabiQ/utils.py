labels = ["أ", "ب", "ج", "د", "هـ", "و", "ز", "ح", "ط", "ي"]
def doc_to_text(doc):
    return (
        "This is a multiple choice question, choose the correct option. "
        "The output should consist only of the single letter of the correct answer with no explanation.\n"
        f"{doc['prompt']}"
    )

def doc_to_choice(doc):
    return [labels[i] for i in range(len(doc["choices"]))]

def doc_to_target(doc):
    options = doc_to_choice(doc)
    return options[doc["index"]]


